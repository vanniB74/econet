// ========== TRANSLATION HELPER FUNCTIONS ==========
function getTranslation(lang, key) {
  return T[lang]?.[key] || T.it?.[key] || key;
}

function translatePage(lang) {
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    el.textContent = getTranslation(lang, key);
  });

  // Update form placeholders
  const nameInput = document.getElementById('userName');
  const emailInput = document.getElementById('userEmail');
  const phoneInput = document.getElementById('userPhone');

  if (nameInput) nameInput.placeholder = getTranslation(lang, 'form_name_placeholder');
  if (emailInput) emailInput.placeholder = getTranslation(lang, 'form_email_placeholder');
  if (phoneInput) phoneInput.placeholder = getTranslation(lang, 'form_phone_placeholder');

  // Update language selector UI
  const flagMap = {
    it: '🇮🇹',
    en: '🇬🇧',
    fr: '🇫🇷',
    de: '🇩🇪',
  };

  const codeMap = {
    it: 'IT',
    en: 'EN',
    fr: 'FR',
    de: 'DE',
  };

  const currentLangFlag = document.getElementById('currentLangFlag');
  const currentLangCode = document.getElementById('currentLangCode');

  if (currentLangFlag) currentLangFlag.textContent = flagMap[lang] || '🌍';
  if (currentLangCode) currentLangCode.textContent = codeMap[lang] || lang.toUpperCase();
}
